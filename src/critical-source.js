const bySource=new Map(criticalSourceCorrections.map(entry=>[entry.original.description+"\u0000"+entry.original.effect,entry]));
export function normalizedCriticalCell(cell) {
  const correction=bySource.get(cell?.description+"\u0000"+cell?.effect);
  return correction ? {...cell,...correction.corrected,sourceCorrection:correction} : cell;
}
export function normalizedCriticalTable(table) {
  if(table?.kind!=='critical')return table;
  return {...table,rows:table.rows.map(row=>({...row,cells:row.cells.map(normalizedCriticalCell)}))};
}
